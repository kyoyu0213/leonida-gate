// 連絡先の種別（friendContactKindLabelKey が返す 'fr.ck.*'）に対応するアプリ／
// プラットフォームのブランドアイコン。「連絡先」だけでは何のIDか分かりづらいので、
// PSN・Discord などのロゴを添えて一目で分かるようにする。
// ブランドSVGは単色（currentColor）。色は className の text-* で指定する。

type Kind = 'psn' | 'xbox' | 'rockstar' | 'discord' | 'discordLink' | 'link' | 'gameId';

/** 'fr.ck.psn' などのラベルキーから種別を取り出す。未知は 'gameId'。 */
export function contactKindFromKey(kindKey: string | null): Kind {
  const k = (kindKey ?? '').replace('fr.ck.', '');
  if (k === 'psn' || k === 'xbox' || k === 'rockstar' || k === 'discord' || k === 'discordLink' || k === 'link')
    return k as Kind;
  return 'gameId';
}

